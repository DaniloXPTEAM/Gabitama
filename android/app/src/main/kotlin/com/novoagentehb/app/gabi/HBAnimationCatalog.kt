package com.novoagentehb.app.gabi

/**
 * Registro central de mídias, fases e animações da HB (`HBAnimationCatalog`):
 * - Mantém todas as mídias aprovadas da origem `voz-latencia` e integra as mídias originais
 *   baixadas da pasta `Avatar` do Google Drive (R1.3) com metadados reais verificados.
 * - Registra explicitamente pendências ausentes no Drive/repositório (`gabi-spritesheet.png` e
 *   cenas dedicadas ainda não enviadas), sem inventar estados fictícios ou regras de evolução.
 */
enum class HBMediaFormat {
    MP4_VIDEO,
    WEBP_SEQUENCE,
    PNG_SEQUENCE,
    PNG_STATIC_FALLBACK,
    PNG_SPRITESHEET,
    PNG_CHARACTER_BIBLE,
    ASSET_PENDING
}

enum class HBInterruptionPolicy {
    IMMEDIATE_PREEMPT,
    COMPLETE_OR_PREEMPT_VOICE,
    TRANSIENT_RETURN_TO_PREVIOUS
}

enum class HBMediaAvailability {
    AVAILABLE_NATIVE_VIDEO,
    AVAILABLE_NATIVE_SEQUENCE,
    AVAILABLE_STATIC_REFERENCE,
    REUSED_APPROVED_SEQUENCE,
    STATIC_BREATH_FALLBACK,
    PENDING_FLOW_MEDIA
}

enum class HBCatalogStateId {
    IDLE,
    LISTENING,
    LISTENING_INTENT,
    THINKING,
    COMPUTER_THINKING,
    TALKING,
    WORKING,
    EATING,
    EATING_REACTION,
    READING,
    SLEEPING,
    MUSIC_REACTION,
    TAP_REACTION,
    SUCCESS,
    ERROR,
    CANCELLED,
    OUTFIT_CHANGE,
    ROOM_INTRO_MP4,
    ROOM_BG_LOOP_MP4,
    STAGE_PRE_ADOLESCENT_IDLE,
    STAGE_ADOLESCENT_IDLE,
    SPRITESHEET_OPTIONAL,
    BIBLE_CHARACTER_SHEET
}

